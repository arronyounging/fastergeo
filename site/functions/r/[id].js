export async function onRequestGet({ params, env, request }) {
  const lang = new URL(request.url).searchParams.get('lang') === 'zh' ? 'zh' : null;
  const rec = await loadScan(env, params.id).catch(() => null);
  const t = T[lang ?? (rec?.lang === 'zh' ? 'zh' : 'en')];
  const head = (title, desc) => `<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:type" content="article">
<meta name="twitter:card" content="summary_large_image">`;

  if (!rec) {
    return new Response(page(t, `<h1>${t.gone}</h1><p><a href="/">${t.rescan}</a></p>`,
      head('FasterGEO', t.gone), 'FasterGEO'), { status: 404, headers: html() });
  }

  const p = rec.page, q = rec.probe;
  const brand = q?.brand ?? new URL(rec.url).hostname;
  const title = t.title(brand);
  // The preview card carries the finding itself — this link's whole job is to
  // survive being forwarded, and the quote is what makes someone open it.
  const desc = q ? q.answer.replace(/\s+/g, ' ').slice(0, 180) : `${p.score}/100 · ${t.reads(p.wordCount)}`;

  const said = q ? `<section class="said v-${q.verdict === 'knows' ? 'good' : q.verdict === 'unverified' ? 'mid' : 'bad'}">
      <div class="q">${esc(q.question)}</div>
      <blockquote>${esc(q.answer)}</blockquote>
      <div class="foot"><b>${esc(t.verdict[q.verdict] ?? '')}</b> · ${t.asked} · ${esc(rec.createdAt.slice(0, 10))}</div>
      <div class="fine">${t.one}</div>
    </section>` : '';

  const body = `${said}
    <section class="card">
      <div class="score"><span class="grade g-${esc(p.grade)}">${esc(p.grade)}</span>
        <div><b>${p.score}</b><small>/100 · ${esc(t.reads(p.wordCount))}</small>
        <div class="url">${esc(rec.url)}</div></div></div>
    </section>
    <section class="watch" id="watch">
      <h2>${t.watchH}</h2><p>${t.watchP}</p>
      <form id="wf"><input id="we" type="email" required placeholder="${esc(t.ph)}" autocomplete="email">
        <button type="submit">${t.watchBtn}</button></form>
      <div id="wm" class="wm"></div>
    </section>
    <section class="deeper"><h2>${t.deeper}</h2><p>${t.deeperP}</p>
      <code>npx fastergeo start ${esc(new URL(rec.url).hostname)}</code></section>
    <footer>${t.made}</footer>
    <script>
    document.getElementById('wf').addEventListener('submit', async e => {
      e.preventDefault();
      const m = document.getElementById('wm');
      m.textContent = '…';
      const r = await fetch('/api/watch', { method:'POST', headers:{'Content-Type':'application/json'},
        body: JSON.stringify({ id: ${JSON.stringify(rec.id)}, email: document.getElementById('we').value }) });
      const d = await r.json().catch(() => ({}));
      m.textContent = r.ok ? ${JSON.stringify(t.watchOk)} : (d.error || 'failed');
      m.className = 'wm ' + (r.ok ? 'ok' : 'err');
    });
    </script>`;
  return new Response(page(t, body, head(title, desc), title), { headers: html() });
}

