/**
 * GET /r/<id> — the report URL, which is the console.
 *
 * No login and no app: the thing a person returns to, and the thing they paste
 * into a chat window, is a link. Server-rendered rather than a client fetch for
 * one reason that matters more than the rest — Open Graph. This link exists to
 * be forwarded, and a preview card carrying the actual finding is worth more
 * than any copy on the page it links to.
 *
 * The discipline of the scan card carries over unchanged: the verbatim quote
 * comes before the score, an unproven verdict says "read it yourself", and one
 * probe is described as one probe.
 */
import { loadScan } from '../api/_store.js';

const esc = s => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

