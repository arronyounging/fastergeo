/**
 * GET /r/<id> — the workbench, on the web.
 *
 * The four-pane workbench existed only as `fastergeo ui` on 127.0.0.1, which is
 * a strange place to put the panel when the paid proposition is "you do not
 * have to open a terminal". This is that panel, at a URL: profile, evidence,
 * what to fix today, and what we can watch for you.
 *
 * Still no login. The link is the console — the thing you return to and the
 * thing you paste into a chat window — and it is server-rendered so the Open
 * Graph card carries the finding itself, because being forwarded is most of
 * what this page is for.
 *
 * The CLI's discipline carries over unchanged: the verbatim quote before the
 * score, an unproven verdict that says "read it yourself", every ticket
 * carrying what "done" has to look like, and a dash wherever nothing was
 * measured.
 */
import { loadScan } from '../api/_store.js';

const clean = s => String(s ?? '').replace(/[*_`#]+/g, '').replace(/[ \t]+/g, ' ').trim();
const esc = s => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

