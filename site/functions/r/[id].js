export async function onRequestGet({ params, env, request }) {
  const forced = new URL(request.url).searchParams.get('lang');
  const rec = await loadScan(env, params.id).catch(() => null);
  const lang = forced === 'zh' ? 'zh' : forced === 'en' ? 'en' : (rec?.lang === 'zh' ? 'zh' : 'en');
  const t = T[lang];
  const meta = (title, desc) => `<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:type" content="article"><meta name="twitter:card" content="summary_large_image">`;

  if (!rec) {
    return new Response(page(`<section><h1>${t.gone}</h1><p><a href="/">${t.rescan}</a></p></section>`,
      meta('FasterGEO', t.gone), 'FasterGEO'), { status: 404, headers: html() });
  }

  const p = rec.page, q = rec.probe, site = rec.site, tickets = rec.tickets ?? [];
  const host = new URL(rec.url).hostname;
  const brand = q?.brand ?? host;
  const desc = q ? clean(q.answer).slice(0, 180) : `${p.score}/100 · ${t.reads(p.wordCount)}`;
  const vclass = !q ? 'mid'
    : q.verdict === 'knows' ? 'good' : q.verdict === 'unverified' ? 'mid' : 'bad';

  const dims = (p.dimensions ?? []).map(d => {
    const na = d.score === null || d.score === undefined;
    const pctv = na ? 0 : Math.round((d.score / d.max) * 100);
    return `<div class="dim${!na && pctv < 40 ? ' low' : ''}">
      <span>${esc(DIMS[lang][d.key] ?? d.key)}</span>
      <span class="bar"><i style="width:${pctv}%"></i></span>
      <span class="v">${na ? `<em>${t.notMeasured}</em>` : `${d.score}/${d.max}`}</span></div>`;
  }).join('');

  const chk = (ok, label) => `<span class="${ok ? 'ok' : 'no'}">${ok ? '✓' : '✗'} ${label}</span>`;
  const checks = site ? `<div class="checks">
    ${chk(site.robotsTxtFound, 'robots.txt')}
    ${chk(!(site.blockedSearchCrawlers ?? site.blockedAiCrawlers ?? []).length, lang === 'zh' ? 'AI 爬虫未被封' : 'AI crawlers allowed')}
    ${chk(site.sitemapFound, 'sitemap')} ${chk(site.llmsTxtFound, 'llms.txt')}</div>` : '';

  // Every ticket carries what "done" has to look like. That line is the whole
  // difference between a recommendation and something you can check later.
  const cards = tickets.map((k, i) => `<details class="tk"${i === 0 ? ' open' : ''}>
      <summary><span class="pr pr-${esc(k.priority)}">${esc(k.priority)}</span>
        <b>${esc(k.title)}</b></summary>
      ${k.rationale ? `<p class="why">${esc(k.rationale)}</p>` : ''}
      <p class="acc"><b>${t.doneWhen}:</b> ${esc(k.acceptance?.desc ?? '—')}</p>
      ${k.fixHint ? `<pre class="hint">${esc(k.fixHint)}</pre>` : ''}
    </details>`).join('');

  const body = `
  <div class="bar">
    <span class="dot"></span><b>${esc(brand)}</b>
    <span class="meta">${esc(host)} · ${t.scanned} ${esc(rec.createdAt.slice(0, 10))}</span>
    <span class="sp"></span><a class="btn" href="/${lang === 'zh' ? 'zh/' : ''}#scan">${t.rescan}</a>
  </div>
  <div class="panes">
    <section class="pane">
      <h2>${t.evidence}</h2>
      ${q ? `<div class="said v-${vclass}">
          <div class="q">${esc(q.question)}</div>
          <blockquote>${esc(clean(q.answer))}</blockquote>
          <div class="foot"><b>${esc(t.verdict[q.verdict] ?? '')}</b> · ${t.asked}</div>
          <div class="fine">${t.one}</div>
        </div>` : `<p class="fine">${t.quoteMissing}</p>`}
      <div class="score"><span class="grade g-${esc(p.grade)}">${esc(p.grade)}</span>
        <div><b>${p.score}</b><small>/100 · ${esc(t.readiness)}</small>
          <div class="fine">${esc(t.reads(p.wordCount))}</div></div></div>
      <div class="dims">${dims}</div>
      ${checks}
      <p class="fine">${t.dash}</p>
    </section>
    <div class="col">
      <section class="pane">
        <h2>${t.today} <span class="n">${t.fixCount(tickets.length)}</span></h2>
        ${cards || `<p class="fine">${t.noTickets}</p>`}
      </section>
      <section class="pane watch">
        <h2>${t.watchH}</h2><p>${t.watchP}</p>
        ${rec.email ? `<p class="okmsg">${t.watching}</p>` : `
        <form id="wf"><input id="we" type="email" required placeholder="${esc(t.ph)}" autocomplete="email">
          <button type="submit">${t.watchBtn}</button></form><div id="wm" class="wm"></div>`}
      </section>
      <section class="pane">
        <h2>${t.deeper}</h2><p>${t.deeperP}</p>
        <code>npx fastergeo start ${esc(host)}</code>
      </section>
    </div>
  </div>
  <footer>${t.made}</footer>
  ${rec.email ? '' : `<script>
  document.getElementById('wf').addEventListener('submit', async e => {
    e.preventDefault();
    const m = document.getElementById('wm'); m.textContent = '…';
    const r = await fetch('/api/watch', { method:'POST', headers:{'Content-Type':'application/json'},
      body: JSON.stringify({ id: ${JSON.stringify(rec.id)}, email: document.getElementById('we').value }) });
    const d = await r.json().catch(() => ({}));
    m.textContent = r.ok ? ${JSON.stringify(t.watchOk)} : (d.error || 'failed');
    m.className = 'wm ' + (r.ok ? 'ok' : 'err');
  });</script>`}`;
  return new Response(page(body, meta(t.title(brand), desc), t.title(brand)), { headers: html() });
}

