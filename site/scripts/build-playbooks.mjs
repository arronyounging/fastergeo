#!/usr/bin/env node
/**
 * Bundle the marketing skills suite into something the edge can serve.
 *
 *   node site/scripts/build-playbooks.mjs [--src ~/.agents/skills]
 *
 * The suite is 21k lines across 71 directories. A Worker cannot read a
 * filesystem, and shipping all of it inline would bloat every deploy for
 * content most requests never touch. So each skill is reduced to the part a
 * person acts on — the headed sections — and written as one JSON file the
 * Functions build can import.
 *
 * MIT licensed (coreyhaines31/marketingskills). The notice travels with the
 * data rather than living in a file nobody reads, so any surface that renders a
 * playbook necessarily has the attribution to hand.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const HERE = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const srcFlag = args.indexOf('--src');
const SRC = srcFlag >= 0 ? args[srcFlag + 1] : join(homedir(), '.agents', 'skills');
// Emitted as a JS module rather than JSON: the Functions bundler resolves
// module imports reliably, and a .json import silently fell through to the
// static asset handler at deploy time — the endpoint returned the homepage.
const OUT = join(HERE, '..', 'functions', 'api', '_playbooks.js');
/** Per-section cap. The Worker bundle has a hard size limit and every deploy
 *  pays for this, so depth is traded against breadth here and nowhere else. */
const SECTION_CHARS = 2200;

/**
 * Everything the suite ships. An earlier version carried a hand-picked 18 on the
 * argument that a playbook for something we never surface is dead weight — that
 * was me deciding for the customer which parts of a marketing system they are
 * allowed to want. The whole suite is the capability; the panel decides what to
 * put in front of you, and the bundle should never be the thing that limits it.
 *
 * Cost of carrying all of it is bounded by SECTION_CHARS below, not by the
 * number of skills, which is why this is affordable.
 */
const WANTED = readdirSync(SRC, { withFileTypes: true })
  .filter(d => d.isDirectory() && existsSync(join(SRC, d.name, 'SKILL.md')))
  .map(d => d.name)
  .sort();

/** A section is worth carrying if it tells someone what to do. */
function sections(md) {
  const out = [];
  const lines = md.split('\n');
  let cur = null;
  let inFence = false;
  for (const line of lines) {
    if (/^```/.test(line)) inFence = !inFence;
    const h = !inFence && /^(#{2,3})\s+(.+)$/.exec(line);
    if (h) {
      if (cur) out.push(cur);
      cur = { level: h[1].length, heading: h[2].trim(), body: [] };
      continue;
    }
    if (cur) cur.body.push(line);
  }
  if (cur) out.push(cur);
  return out
    .map(s => ({ ...s, body: s.body.join('\n').trim() }))
    .filter(s => s.body.length > 80);
}

function frontmatter(md) {
  const m = /^---\n([\s\S]*?)\n---/.exec(md);
  if (!m) return {};
  const desc = /description:\s*["']?([\s\S]*?)["']?\s*\n(?:[a-z]|---)/i.exec(m[1] + '\n---');
  return { description: desc ? desc[1].replace(/\s+/g, ' ').trim() : '' };
}

if (!existsSync(SRC)) {
  console.error(`No suite at ${SRC}. Install it first:\n  npx skills add coreyhaines31/marketingskills`);
  process.exit(1);
}

const bundle = {
  source: 'coreyhaines31/marketingskills',
  license: 'MIT',
  attribution: 'Marketing skills by Corey Haines — MIT licensed.',
  builtAt: new Date().toISOString().slice(0, 10),
  skills: {},
};

for (const name of WANTED) {
  const p = join(SRC, name, 'SKILL.md');
  if (!existsSync(p)) { console.warn(`  skip ${name} (not installed)`); continue; }
  const md = readFileSync(p, 'utf8');
  const fm = frontmatter(md);
  const secs = sections(md);
  bundle.skills[name] = {
    // Trimmed: the routing text is written for an agent's tool picker and reads
    // as keyword soup to a person. One sentence is all a human needs.
    about: fm.description.split(/\.\s/)[0].replace(/^When the user (wants to |needs to )?/i, '').slice(0, 200),
    sections: secs.map(s => ({ h: s.heading, b: s.body.slice(0, SECTION_CHARS) })),
  };
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `/**\n * Playbook bundle — generated by scripts/build-playbooks.mjs, do not edit.\n`
  + ` * Source: ${bundle.source} (${bundle.license}). ${bundle.attribution}\n */\n`
  + `export default ${JSON.stringify(bundle)};\n`);
const kb = Math.round(readFileSync(OUT).length / 1024);
console.log(`\n  ${Object.keys(bundle.skills).length} playbooks · ${Object.values(bundle.skills).reduce((n, s) => n + s.sections.length, 0)} sections · ${kb} KB`);
console.log(`  → ${OUT}\n`);
